#!/usr/bin/env python3
"""Write yazi/theme.toml: srd-base.toml plus yazi's own icon rules turned grey (stdlib only).

  python -I yazi/make-theme.py [--yazi /usr/bin/yazi] [--out yazi/theme.toml]

yazi keeps its default icon rules inside its binary; they colour each icon with a hex value,
which bypasses the terminal palette. This copies the [icon] section of the installed yazi's
dark preset and maps every hex colour to a grey of the same luminance, kept between #767676
(4.62:1 on black) and #e6e6e6 so every icon stays readable. Run it again after a yazi update.
"""
import argparse
import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
LO, HI = 0x76, 0xE6


def icon_section(binary):
    data = Path(binary).read_bytes()
    start = data.find(b"\n[icon]\n")
    if start < 0:
        raise SystemExit(f"{binary}: no [icon] section found")
    end = data.find(b"\n# : }}}", start)
    return data[start + 1:end].decode()


def grey(match):
    h = match.group(1)
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    y = round(0.2126 * r + 0.7152 * g + 0.0722 * b)
    v = LO + y * (HI - LO) // 255
    return f'"#{v:02x}{v:02x}{v:02x}"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--yazi", default=shutil.which("yazi") or "/usr/bin/yazi")
    ap.add_argument("--out", default=str(HERE / "theme.toml"))
    args = ap.parse_args()
    icons = re.sub(r'"#([0-9a-fA-F]{6})"', grey, icon_section(args.yazi))
    base = (HERE / "srd-base.toml").read_text()
    Path(args.out).write_text(
        base + "\n# Generated by make-theme.py from yazi's built-in icon rules, colours turned grey.\n" + icons + "\n")
    print(f"wrote {args.out} ({icons.count(chr(10))} icon lines)")


if __name__ == "__main__":
    main()
